def main() -> None:
    course = json.loads(COURSE.read_text(encoding="utf-8"))
    course["modules"] = MODULES

    # Preserve question bank; replace lessons entirely in canonical order
    ordered_ids = [lid for m in MODULES for lid in m["lessonIds"]]
    course["lessons"] = []
    for lid in ordered_ids:
        data = LESSONS[lid]
        course["lessons"].append({"id": lid, **data})

    COURSE.write_text(json.dumps(course, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    shutil.copyfile(COURSE, PUBLIC)

    total_blocks = sum(len(l["blocks"]) for l in course["lessons"])
    total_cards = sum(len(l["cards"]) for l in course["lessons"])
    total_chars = 0
    for l in course["lessons"]:
        for b in l["blocks"]:
            total_chars += len(b.get("content") or "")
            total_chars += len(b.get("title") or "")
            total_chars += sum(len(x) for x in (b.get("items") or []))

    print(f"Lessons: {len(course['lessons'])}")
    print(f"Blocks: {total_blocks}, cards: {total_cards}, content chars≈{total_chars}")
    for l in course["lessons"]:
        chars = 0
        for b in l["blocks"]:
            chars += len(b.get("content") or "") + len(b.get("title") or "")
            chars += sum(len(x) for x in (b.get("items") or []))
        print(f"  {l['id']:22} blocks={len(l['blocks']):2} cards={len(l['cards']):2} chars={chars:5}")


